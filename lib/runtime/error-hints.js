/**
 * @param {string|null|undefined} message 機器・sequencer の文言
 * @returns {string|null} 何をすればよいかの 1 行。分からなければ null
 */
function hintOf(message) {
  if (message === null || message === undefined) return null
  const s = String(message)
  if (!s) return null
  for (const h of HINTS) if (h.re.test(s)) return h.hint
  return null
}

